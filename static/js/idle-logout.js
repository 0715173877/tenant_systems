/**
 * Tenant Systems - Idle / Tab-Close / Browser-Close Auto Logout
 *
 * Two independent guards run from this file:
 *
 *  1. Tab guard - browsers give the server no signal when a *tab* is closed,
 *     so each tab carries a sessionStorage marker. Unauthenticated pages stamp
 *     the marker (see templates/base.html); an authenticated page that is
 *     missing the marker was closed and reopened (or is a brand new tab), so
 *     the user is signed out and must log in again.
 *
 *  2. Idle guard - after a period of inactivity the user is warned and then
 *     signed out. The server side (SESSION_COOKIE_AGE,
 *     SESSION_SAVE_EVERY_REQUEST and SESSION_EXPIRE_AT_BROWSER_CLOSE in
 *     config/settings.py) remains the source of truth.
 *
 * Configuration is provided by templates/base.html through window.APP_IDLE:
 *   { timeoutMs, warningMs, logoutOnTabClose, logoutUrl, heartbeatUrl }
 */
(function () {
  "use strict";

  var cfg = window.APP_IDLE || {};
  var timeoutMs = parseInt(cfg.timeoutMs, 10) || 0;
  var TAB_MARKER_KEY = "ts_tab_session";

  // A tab is only "known" if the marker set by an unauthenticated page is still
  // present. If sessionStorage is unavailable we never lock the user out.
  function hasTabMarker() {
    try {
      return sessionStorage.getItem(TAB_MARKER_KEY) !== null;
    } catch (e) {
      return true;
    }
  }

  /* ------------------------------------------------------------------ *
   * Shared logout helper
   * ------------------------------------------------------------------ */

  function getCookie(name) {
    var match = document.cookie.match(
      "(?:^|;)\\s*" + name.replace(/([.*+?^${}()|[\]\\])/g, "\\$1") + "\\s*=\\s*([^;]+)"
    );
    return match ? decodeURIComponent(match.pop()) : null;
  }

  var loggingOut = false;

  function doLogout(reason) {
    if (loggingOut || !cfg.logoutUrl) {
      return;
    }
    loggingOut = true;

    var form = document.createElement("form");
    form.method = "post";
    form.action = cfg.logoutUrl;

    var csrf = getCookie("csrftoken");
    if (csrf) {
      var csrfInput = document.createElement("input");
      csrfInput.type = "hidden";
      csrfInput.name = "csrfmiddlewaretoken";
      csrfInput.value = csrf;
      form.appendChild(csrfInput);
    }

    var reasonInput = document.createElement("input");
    reasonInput.type = "hidden";
    reasonInput.name = "reason";
    reasonInput.value = reason;
    form.appendChild(reasonInput);

    document.body.appendChild(form);
    form.submit();
  }

  /* ------------------------------------------------------------------ *
   * 1. Tab guard - sign out when a closed tab is reopened
   * ------------------------------------------------------------------ */

  if (cfg.logoutOnTabClose !== false && !loggingOut && !hasTabMarker()) {
    // This tab never passed through the login screen -> it was closed and
    // reopened (or is a second tab). End the session before rendering anything.
    doLogout("tab");
    return;
  }

  /* ------------------------------------------------------------------ *
   * 2. Idle guard - warn, then sign out after inactivity
   * ------------------------------------------------------------------ */

  // Idle logout disabled or misconfigured -> tab guard was all we needed.
  if (!timeoutMs) {
    return;
  }

  var warningMs = Math.min(parseInt(cfg.warningMs, 10) || 0, timeoutMs);
  var CHECK_INTERVAL_MS = 1000;
  var ACTIVITY_EVENTS = [
    "mousemove",
    "mousedown",
    "click",
    "keydown",
    "scroll",
    "wheel",
    "touchstart",
    "touchmove",
  ];

  var lastActivity = Date.now();
  var warningShown = false;
  var modalEl = null;
  var countdownEl = null;

  function now() {
    return Date.now();
  }

  function remaining() {
    return timeoutMs - (now() - lastActivity);
  }

  function resetActivity() {
    lastActivity = now();
    if (warningShown) {
      hideWarning();
    }
  }

  function onActivity() {
    // Ignore activity generated by the actual logout for a smooth hand-off.
    if (loggingOut) {
      return;
    }
    resetActivity();
  }

  ACTIVITY_EVENTS.forEach(function (evt) {
    document.addEventListener(evt, onActivity, { passive: true });
  });

  // When the user comes back to the tab, re-evaluate immediately.
  document.addEventListener("visibilitychange", function () {
    if (!document.hidden) {
      checkIdle();
    }
  });

  function checkIdle() {
    if (loggingOut) {
      return;
    }
    var left = remaining();
    if (left <= 0) {
      doLogout("idle");
      return;
    }
    if (left <= warningMs && !warningShown) {
      showWarning();
    }
    if (warningShown) {
      updateCountdown(left);
    }
  }

  function updateCountdown(left) {
    if (countdownEl) {
      countdownEl.textContent = String(Math.max(0, Math.ceil(left / 1000)));
    }
  }

  function buildModal() {
    var wrapper = document.createElement("div");
    wrapper.className = "modal fade";
    wrapper.tabIndex = -1;
    wrapper.setAttribute("aria-hidden", "true");
    wrapper.innerHTML =
      '<div class="modal-dialog modal-dialog-centered">' +
      '<div class="modal-content">' +
      '<div class="modal-header">' +
      '<h5 class="modal-title"><i class="bi bi-clock-history me-2 text-warning"></i>Still there?</h5>' +
      "</div>" +
      '<div class="modal-body">' +
      '<p class="mb-2">For your security you will be signed out in ' +
      '<strong><span id=\"idleLogoutCountdown\">--</span> seconds</strong> because no activity was detected.</p>' +
      '<p class="text-muted small mb-0">Select "Stay signed in" to continue working.</p>' +
      "</div>" +
      '<div class="modal-footer">' +
      '<button type="button" class="btn btn-outline-secondary" id="idleLogoutNowBtn">Sign out now</button>' +
      '<button type="button" class="btn btn-primary" id="idleStayBtn">Stay signed in</button>' +
      "</div>" +
      "</div>" +
      "</div>";
    document.body.appendChild(wrapper);

    modalEl = wrapper;
    countdownEl = wrapper.querySelector("#idleLogoutCountdown");
    wrapper
      .querySelector("#idleStayBtn")
      .addEventListener("click", staySignedIn);
    wrapper
      .querySelector("#idleLogoutNowBtn")
      .addEventListener("click", function () {
        doLogout("idle");
      });
  }

  function showModal() {
    if (!modalEl) {
      buildModal();
    }
    if (window.bootstrap && window.bootstrap.Modal) {
      window.bootstrap.Modal.getOrCreateInstance(modalEl).show();
    }
  }

  function hideModal() {
    if (modalEl && window.bootstrap && window.bootstrap.Modal) {
      window.bootstrap.Modal.getOrCreateInstance(modalEl).hide();
    }
  }

  function showWarning() {
    warningShown = true;
    showModal();
    updateCountdown(remaining());
  }

  function hideWarning() {
    warningShown = false;
    hideModal();
  }

  function staySignedIn() {
    resetActivity();
    hideWarning();
    // Ping the server so the *server-side* session expiry slides forward too.
    if (cfg.heartbeatUrl) {
      fetch(cfg.heartbeatUrl + "?_=" + now(), {
        method: "GET",
        credentials: "same-origin",
        headers: { "X-Requested-With": "XMLHttpRequest" },
      }).catch(function () {
        /* heartbeat is best-effort */
      });
    }
  }

  // Poll on an interval rather than relying on a single long setTimeout so the
  // timer stays correct across device sleep / tab throttling.
  setInterval(checkIdle, CHECK_INTERVAL_MS);
})();
